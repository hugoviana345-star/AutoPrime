import os
import sqlite3
import sys
from pathlib import Path
import psycopg
from psycopg.rows import dict_row

origem = Path(__file__).parent / 'lib' / 'backend' / 'autoprime.db'
dsn = os.getenv('DATABASE_URL')
if not dsn:
    sys.exit('Defina DATABASE_URL antes de executar a migração.')
if not origem.exists():
    sys.exit(f'Banco SQLite não encontrado: {origem}')

sqlite = sqlite3.connect(origem)
sqlite.row_factory = sqlite3.Row
with psycopg.connect(dsn, row_factory=dict_row) as pg:
    pg.execute('''CREATE TABLE IF NOT EXISTS usuarios (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE, senha_hash TEXT, visitante INTEGER NOT NULL DEFAULT 0, administrador INTEGER NOT NULL DEFAULT 0, nome TEXT NOT NULL DEFAULT '', telefone TEXT NOT NULL DEFAULT '', foto TEXT NOT NULL DEFAULT '')''')
    pg.execute('''CREATE TABLE IF NOT EXISTS sessoes (token_hash TEXT PRIMARY KEY, usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE, expira BIGINT NOT NULL)''')
    pg.execute('''CREATE TABLE IF NOT EXISTS produtos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome TEXT NOT NULL, descricao TEXT NOT NULL, categoria TEXT NOT NULL, preco_centavos BIGINT NOT NULL CHECK(preco_centavos > 0), imagem TEXT NOT NULL, ativo INTEGER NOT NULL DEFAULT 1)''')
    pg.execute('''CREATE TABLE IF NOT EXISTS carrinho (usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE, produto_id TEXT NOT NULL, quantidade INTEGER NOT NULL CHECK(quantidade BETWEEN 1 AND 999), PRIMARY KEY(usuario_id, produto_id))''')
    for table in ('usuarios','produtos'):
        try: rows = sqlite.execute(f'SELECT * FROM {table}').fetchall()
        except sqlite3.OperationalError: rows = []
        for row in rows:
            cols = list(row.keys()); vals = [row[c] for c in cols]
            pg.execute(f"INSERT INTO {table} ({','.join(cols)}) VALUES ({','.join(['%s']*len(cols))}) ON CONFLICT (id) DO NOTHING", vals)
    for table in ('sessoes','carrinho'):
        try: rows = sqlite.execute(f'SELECT * FROM {table}').fetchall()
        except sqlite3.OperationalError: rows = []
        for row in rows:
            cols = list(row.keys()); vals = [row[c] for c in cols]
            pg.execute(f"INSERT INTO {table} ({','.join(cols)}) VALUES ({','.join(['%s']*len(cols))}) ON CONFLICT DO NOTHING", vals)
    for table in ('usuarios','produtos'):
        pg.execute(f"SELECT setval(pg_get_serial_sequence('{table}','id'), COALESCE((SELECT MAX(id) FROM {table}), 1), true)")
sqlite.close()
print('Migração concluída. Confira os registros no PostgreSQL antes de publicar.')
